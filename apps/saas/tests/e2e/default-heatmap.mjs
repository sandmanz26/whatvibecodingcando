// Demo-mode check (no server): onboarding with Heatmaps → Open my site → clicks show on the heatmap without
// creating a study → Copy invite link opens the consent screen. Run: npm run build (root); node serve.mjs &; node default-heatmap.mjs
// (playwright must be resolvable; set executablePath if the default Chromium is missing).
import { chromium } from 'playwright'
import fs from 'fs'
const b = await chromium.launch().catch(() => chromium.launch({ executablePath: "/opt/pw-browsers/chromium" }))
const ctx = await b.newContext({ permissions: ['clipboard-read', 'clipboard-write'] })
const pg = await ctx.newPage()
pg.on('pageerror', (e) => console.log('ERR', e.message))
await pg.goto('http://localhost:8080/app#/register')
await pg.getByLabel('Your name').fill('Tess')
await pg.getByLabel('Work email').fill('tess@example.com')
const pw = pg.locator('input[type=password]'); for (let i = 0; i < await pw.count(); i++) await pw.nth(i).fill('correct horse battery 9')
await pg.getByRole('button', { name: 'Create account' }).click()
await pg.waitForTimeout(1500)
const heat = pg.locator('button.lp-check', { hasText: 'Heatmaps' })
console.log('heat sub:', await heat.innerText())
if ((await heat.getAttribute('aria-pressed')) !== 'true') await heat.click()
await pg.getByRole('button', { name: /Continue/ }).click()
await pg.getByLabel('Project name').fill('Mint shop')
await pg.getByPlaceholder('localhost:3000').fill('localhost:3000')
await pg.getByRole('button', { name: /Create project/ }).click()
await pg.waitForTimeout(2500)
const html = await pg.content()
const pid = /data-project=(?:&quot;|")([\w-]+)/.exec(html)?.[1]
console.log('pid', pid); fs.writeFileSync(new URL('pid', import.meta.url), pid)
await pg.screenshot({ path: '/tmp/onb.png' })
const skip = pg.getByRole('button', { name: /Skip for now|Go to my panel/ }).first(); await skip.click()
await pg.waitForTimeout(1500)
await pg.goto('http://localhost:8080/app#/app'); await pg.waitForTimeout(1500)
const [site] = await Promise.all([ctx.waitForEvent('page'), pg.getByRole('button', { name: /Open my site/ }).first().click()])
site.on('pageerror', (e) => console.log('SITE ERR', e.message))
await site.waitForLoadState(); await site.waitForTimeout(4000)
console.log('site url', site.url())
const note = site.locator('[data-vc-heatnote]'); console.log('note:', await note.count() ? await note.innerText() : 'none')
for (let i = 0; i < 4; i++) { await site.click('#buy'); await site.waitForTimeout(300) }
await site.click('#about')
await site.waitForTimeout(5500)
await site.locator('vibe-collab').locator('button[aria-label="Heatmap"]').click()
await site.waitForTimeout(2500)
const panel = site.locator('vibe-collab .vc-heatpanel')
console.log('PANEL:', (await panel.innerText()).slice(0, 900))
await site.screenshot({ path: '/tmp/heat.png' })
await panel.getByRole('button', { name: 'Copy invite link' }).click(); await site.waitForTimeout(500)
const link = await site.evaluate(() => navigator.clipboard.readText()); console.log('link', link)
// participant in a fresh context
const p2 = await ctx.newPage()
await p2.goto(link); await p2.waitForTimeout(4000)
const card = p2.locator('vibe-collab div').first()
console.log('PARTICIPANT:', (await card.innerText().catch(() => 'none')).slice(0, 400))
await p2.getByRole('button', { name: /I agree/ }).click(); await p2.waitForTimeout(1500)
console.log('AFTER AGREE:', (await card.innerText().catch(() => 'none')).slice(0, 300))
await p2.screenshot({ path: '/tmp/part.png' })
await b.close()
